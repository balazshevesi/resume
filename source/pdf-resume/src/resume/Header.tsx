const ContactIcon = ({ label }: { label: string }) => {
  const path = contactIconPaths[label];

  if (!path) {
    return null;
  }

  return (
    <Svg style={styles.contactIcon} viewBox="0 0 24 24">
      <Path d={path} fill="#050505" />
    </Svg>
  );
};

type ResumeHeaderProps = {
  profile: ResumeData["profile"];
};

// Top profile area of the resume, usually containing the candidate name and contact links.
export const ResumeHeader = ({ profile }: ResumeHeaderProps) => (
  <View style={styles.header}>
    <Text style={styles.name}>{profile.name}</Text>
    <View style={styles.contacts}>
      {profile.contacts.map((contact) => {
        const value = [contact.countryCode, contact.value]
          .filter(Boolean)
          .join(" ");

        return (
          <View key={contact.label} style={styles.contactItem}>
            <ContactIcon label={contact.label} />
            <Text style={styles.contactText}>
              {renderLinkedText(value, contact.href)}
            </Text>
          </View>
        );
      })}
    </View>
  </View>
);
